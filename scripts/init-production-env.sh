#!/bin/sh

set -eu

env_file="${1:-.env}"

if [ -e "$env_file" ]; then
  echo "Refusing to overwrite existing $env_file" >&2
  exit 1
fi

if ! command -v openssl >/dev/null 2>&1; then
  echo "openssl is required to generate production secrets" >&2
  exit 1
fi

umask 077
jwt_secret="$(openssl rand -hex 32)"
csrf_secret="$(openssl rand -hex 32)"
api_key_hash_pepper="$(openssl rand -hex 32)"
version="${EXCALIDASH_VERSION:-$(sed -n '1p' VERSION 2>/dev/null || true)}"
version="${version:-0.6.0}"

{
  printf '%s\n' '# Generated by scripts/init-production-env.sh; keep this file private.'
  printf 'EXCALIDASH_BACKEND_IMAGE=ghcr.io/click-hype/noovicrew-excalidash-backend:%s\n' "$version"
  printf 'EXCALIDASH_FRONTEND_IMAGE=ghcr.io/click-hype/noovicrew-excalidash-frontend:%s\n' "$version"
  printf '%s\n' 'FRONTEND_URL=http://localhost:6767'
  printf '%s\n' 'TRUST_PROXY=false'
  printf '%s\n' 'ENFORCE_HTTPS_REDIRECT=true'
  printf 'JWT_SECRET=%s\n' "$jwt_secret"
  printf 'CSRF_SECRET=%s\n' "$csrf_secret"
  printf 'API_KEY_HASH_PEPPER=%s\n' "$api_key_hash_pepper"
  printf '%s\n' 'ENABLE_AUDIT_LOGGING=true'
  printf '%s\n' 'ENABLE_REFRESH_TOKEN_ROTATION=true'
  printf '%s\n' 'UPDATE_CHECK_OUTBOUND=true'
  printf '%s\n' 'BACKUP_SCHEDULE=0 0 4 * * *'
  printf '%s\n' 'BACKUP_RETENTION_DAYS=14'
} >"$env_file"

chmod 600 "$env_file"
unset jwt_secret csrf_secret api_key_hash_pepper version

echo "Created $env_file with mode 0600. Review FRONTEND_URL and TRUST_PROXY before deployment."
